test('two tabs retry the same offline draft after a sale commits without duplicating it', async ({ page, context }) => {
  await page.goto('/'); await offlineReady(page); await context.setOffline(true)
  await page.getByLabel('Business', { exact: true }).selectOption({ label: 'Bigasan' })
  await page.getByRole('button', { name: 'Sale', exact: true }).click()
  await page.getByLabel('Quantity').fill('5')
  await page.getByLabel('Paid via').selectOption({ label: 'GCash' })
  await expect.poll(async () => (await records(page, 'drafts')).some(d => (d.data as { quantity?: string }).quantity === '5')).toBe(true)
  const second = await context.newPage(); await second.goto('/')
  await second.getByLabel('Business', { exact: true }).selectOption({ label: 'Bigasan' })
  await second.getByRole('button', { name: 'Sale', exact: true }).click()
  await expect(second.getByLabel('Quantity')).toHaveValue('5')
  await page.getByRole('button', { name: 'Finalize sale', exact: true }).click()
  // Observe IndexedDB commit, then close immediately without relying on a success message.
  await expect.poll(async () => (await records(page, 'sales')).length).toBe(1)
  await page.close()
  await second.getByRole('button', { name: 'Finalize sale', exact: true }).click()
  await expect(second.getByText('Sale saved locally.', { exact: false })).toBeVisible()
  expect(await records(second, 'sales')).toHaveLength(1)
  expect(await records(second, 'saleLines')).toHaveLength(1)
  expect(await records(second, 'paymentEntries')).toHaveLength(1)
  expect((await records(second, 'stockMovements')).filter(m => m.reason === 'sale')).toHaveLength(1)
  expect(await records(second, 'outbox')).toHaveLength(1)
  await second.reload()
  await expect(second.getByRole('heading', { name: '₱275.00', exact: true })).toBeVisible()
})

