import { expect, test, type Page } from '@playwright/test'

async function offlineReady(page: Page) {
  await page.evaluate(() => navigator.serviceWorker.ready.then(() => true))
  await page.reload()
  await page.waitForFunction(() => navigator.serviceWorker.controller !== null)
}

async function records(page: Page, table: string, name = 'RRWRS-Demo') {
  return page.evaluate(async ({ table, name }) => {
    const database = await new Promise<IDBDatabase>((resolve, reject) => { const request = indexedDB.open(name); request.onsuccess = () => resolve(request.result); request.onerror = () => reject(request.error) })
    try { return await new Promise<Record<string, unknown>[]>((resolve, reject) => { const tx = database.transaction(table, 'readonly'), request = tx.objectStore(table).getAll(); request.onsuccess = () => resolve(request.result as Record<string, unknown>[]); request.onerror = () => reject(request.error) }) } finally { database.close() }
  }, { table, name })
}

